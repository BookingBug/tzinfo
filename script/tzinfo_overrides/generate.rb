#!/usr/bin/env ruby
# frozen_string_literal: true

# Derives tzinfo 0.3.x zone definitions from a published tzinfo-data 1.x gem.
#
# tzinfo is pinned at 0.3.62 (the last 0.3.x ever released) because
# activesupport 4.0.13 requires tzinfo ~> 0.3.37. 0.3.x compiles its rules into
# the gem and has no DataSource API, so a zone whose rules change upstream stays
# wrong until its definition file is replaced. This emits those replacements.
#
# The two dialects differ mechanically in two ways:
#   * 1.x nests one module deeper (TZInfo::Data::Definitions), so the body
#     dedents by two spaces;
#   * 1.x carries a leading epoch argument on pre-epoch transitions, which 0.3.x
#     derives from the rational that follows it.
#
# The generator also normalises quoted symbols to double quotes and strips
# trailing whitespace. Upstream uses single quotes in both dialects -- the
# double-quoted form is this fork's convention for the corrected definitions,
# which every one of them already follows.
#
# Usage:
#   ruby script/tzinfo_overrides/generate.rb SOURCE_ROOT GEM_VERSION TZDATA_VERSION OUT_ROOT ZONE...
#
#   SOURCE_ROOT     unpacked tzinfo-data gem's lib/tzinfo/data/definitions, or
#                   the same path from a tag of the tzinfo/tzinfo-data repo
#   GEM_VERSION     e.g. 1.2026.5   (recorded in the header; SOURCE_DATA_VERSION
#                                    in lib/tzinfo_overrides.rb of
#                                    BookingBug/bookingbug must match it)
#   TZDATA_VERSION  e.g. 2026e      (recorded in the header)
#   OUT_ROOT        where definitions are written -- lib/tzinfo/definitions in
#                   this repo, which is where the gem loads them from
#
# Re-running it with the same inputs reproduces its own output byte for byte,
# and reproduces the base branch's 23 definitions from 1.2026.3.

HEADER = <<~HDR
  # encoding: UTF-8
  # frozen_string_literal: true

  # Corrected IANA timezone data for %<zone>s.
  #
  # Generated by script/tzinfo_overrides/generate.rb from tzinfo-data %<gem>s (IANA tzdata %<tzdata>s).
  # Do not edit by hand -- re-run the generator instead.
  #
  # This file shadows the definition shipped inside the tzinfo gem, whose
  # copy of the database predates a rule change for this zone.

HDR

PRE_EPOCH = /\A(?<indent>\s*)tz\.transition (?<y>-?\d+), (?<m>\d+), (?<o>:\S+), -?\d+, (?<num>-?\d+), (?<den>\d+)\s*\z/

def convert(text, zone, gem_version, tzdata_version)
  lines = text.split("\n")
  start = lines.index('module TZInfo')
  raise "no 'module TZInfo' line in the definition for #{zone}" unless start
  unless lines[start + 1] == '  module Data'
    raise "expected '  module Data' after 'module TZInfo' for #{zone}, got #{lines[start + 1].inspect}"
  end

  body = lines[(start + 2)..-1]
  body.pop while body.last == ''
  raise "body for #{zone} does not end with the 'module Data' terminator" unless body.last == 'end'
  body.pop

  converted = body.map do |line|
    line = line.sub(/\A  /, '')
    if (m = PRE_EPOCH.match(line))
      line = format('%stz.transition %s, %s, %s, %s, %s',
                    m[:indent], m[:y], m[:m], m[:o], m[:num], m[:den])
    end
    line.gsub(/:'([^']*)'/, ':"\1"').rstrip
  end

  format(HEADER, zone: zone, gem: gem_version, tzdata: tzdata_version) +
    "module TZInfo\n" + converted.join("\n") + "\n"
end

if $PROGRAM_NAME == __FILE__
  source_root, gem_version, tzdata_version, out_root, *zones = ARGV
  abort 'usage: generate.rb SOURCE_ROOT GEM_VERSION TZDATA_VERSION OUT_ROOT ZONE...' if zones.empty?

  require 'fileutils'
  zones.each do |zone|
    src = File.join(source_root, "#{zone}.rb")
    abort "no such definition in the source gem: #{src}" unless File.exist?(src)
    dest = File.join(out_root, "#{zone}.rb")
    FileUtils.mkdir_p(File.dirname(dest))
    File.write(dest, convert(File.read(src), zone, gem_version, tzdata_version))
    puts "  #{zone}"
  end
end
